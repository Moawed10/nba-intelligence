// One-off: copies each team's light and dark logo from the NBA CDN into public/logos so pages never
// hotlink nba.com, and writes the list of teams that have one. Logos are NBA trademarks.
// Usage: node scripts/fetch-team-logos.mjs [api origin, default http://localhost:8000]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const api = process.argv[2] ?? "http://localhost:8000";
const out = join(root, "public", "logos");

const teams = await (await fetch(`${api}/api/v1/teams`)).json();
await mkdir(out, { recursive: true });

const saved = [];
for (const team of teams) {
  let ok = true;
  for (const variant of ["L", "D"]) {
    const response = await fetch(`https://cdn.nba.com/logos/nba/${team.id}/global/${variant}/logo.svg`);
    const body = await response.text();
    const svg = response.ok && /^\s*(<\?xml[^>]*>\s*)?(<!--[\s\S]*?-->\s*)*<svg[\s>]/.test(body) && !/<script|\son\w+=/i.test(body);
    if (!svg) {
      console.warn(`skipped ${team.abbreviation} ${variant}: ${response.status}`);
      ok = false;
      break;
    }
    await writeFile(join(out, `${team.id}-${variant}.svg`), body);
  }
  if (ok) saved.push(team.id);
}

saved.sort((a, b) => a - b);
await writeFile(
  join(root, "src", "components", "brand", "team-logos.ts"),
  `// Generated by scripts/fetch-team-logos.mjs: teams with logos in public/logos.\nexport const TEAM_LOGOS: ReadonlySet<number> = new Set([\n${saved.map((id) => `  ${id},`).join("\n")}\n]);\n`,
);
console.log(`saved ${saved.length} of ${teams.length} teams`);
